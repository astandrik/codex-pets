import {afterEach, expect, it, vi} from "vitest";
import {revisionFixture} from "./animation-revision-fixture.test-utils";
import {petGeneration} from "./service";
import {generationStore} from "./store";
import {GET as fileGet} from "@/app/api/pet-generations/[id]/files/[file]/route";
const origin="https://pets.example";
const context=(id:string)=>({params:Promise.resolve({id})});
const request=(body:unknown,extra:Record<string,string>={})=>new Request(origin+"/revisions",{method:"POST",headers:{origin,"content-type":"application/json","x-pets-client-ip":"203.0.113.9",...extra},body:JSON.stringify(body)});
afterEach(()=>{vi.restoreAllMocks();vi.unstubAllEnvs();});
it("enforces origin, actual body limit and server policy, then recovers the private receipt",async()=>{
  const {POST,GET}=await import("@/app/api/pet-generations/[id]/animation-revisions/route");
  vi.stubEnv("NEXT_PUBLIC_APP_URL",origin);vi.stubEnv("PET_GENERATION_ANIMATION_REVISIONS_ENABLED","true");
  const f=await revisionFixture();
  vi.spyOn(petGeneration,"reviseAnimations").mockImplementation(f.service.reviseAnimations);
  vi.spyOn(petGeneration,"findAnimationRevision").mockImplementation(f.service.findAnimationRevision);
  expect((await POST(request(f.input(),{origin:"https://evil.example"}),context(f.source.id))).status).toBe(403);
  expect((await POST(request({...f.input(),prompt:"x".repeat(17000)}),context(f.source.id))).status).toBe(413);
  expect((await POST(request({...f.input(),states:["look-0-157"]}),context(f.source.id))).status).toBe(400);
  expect((await POST(request({...f.input(),pipelineVersion:1}),context(f.source.id))).status).toBe(400);
  const input=f.input();const response=await POST(request(input),context(f.source.id));expect(response.status).toBe(202);
  expect(response.headers.get("referrer-policy")).toBe("no-referrer");
  const receipt=await GET(new Request(origin+"/revisions?requestId="+input.requestId),context(f.source.id));
  expect((await receipt.json()).generation.generationId).toBe((await response.json()).generation.generationId);
});
it("blocks direct ZIP reads until accepted and rejects cross-origin acceptance",async()=>{
  const {POST}=await import("@/app/api/pet-generations/[id]/animation-revision/accept/route");
  vi.stubEnv("NEXT_PUBLIC_APP_URL",origin);vi.stubEnv("PET_GENERATION_ANIMATION_REVISIONS_ENABLED","true");
  const f=await revisionFixture();const child=await f.service.reviseAnimations(f.source.id,f.input(),"203.0.113.9");
  f.store.jobs.get(child.generationId)!.status="completed";
  f.store.artifacts.set(child.generationId+":pet.zip",{bytes:Buffer.from("zip"),expiresAt:f.config.now+1000});
  vi.spyOn(petGeneration,"get").mockImplementation(f.service.get);
  vi.spyOn(petGeneration,"acceptAnimationRevision").mockImplementation(f.service.acceptAnimationRevision);
  vi.spyOn(generationStore,"readArtifact").mockImplementation((id,kind)=>f.store.readArtifact(id,kind,f.config.now));
  const read=()=>fileGet(new Request(origin),{params:Promise.resolve({id:child.generationId,file:"pet.zip"})});
  expect((await read()).status).toBe(409);
  expect((await POST(new Request(origin,{method:"POST",headers:{origin:"https://evil.example"}}),context(child.generationId))).status).toBe(403);
  expect((await POST(new Request(origin,{method:"POST",headers:{origin}}),context(child.generationId))).status).toBe(200);
  expect((await read()).status).toBe(200);
});
